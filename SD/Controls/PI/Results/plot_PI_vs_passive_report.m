    'Average net absorbed power (W)', ...
    'Interpreter','latex');


title( ...
    'Average Net PTO Power', ...
    'Interpreter','latex');


set( ...
    gca, ...
    'FontName',fontName, ...
    'FontSize',fontSize, ...
    'Box','on');


% Add room above the bars for labels
yTop = max(powerVals);

ylim([ ...
    0, ...
    1.18*yTop]);


