%% plot_PI_vs_passive_report.m
% Publication-quality comparison plots for the passive SD and
% PI-controlled WEC.
%
% Place this script in the PI case folder together with:
%
%   PI_run_ramped.mat
%   passive_SD_run.mat
%
% Expected PI variables in PI_run_ramped.mat:
%   v_ref
%   v_rel
%   error
%   F_PI
%
% Expected passive variable in passive_SD_run.mat:
%   passive.time
%   passive.v_rel
%   passive.Bpto
%   passive.F_pto
%   passive.P_pto
%   passive.float_pos
%   passive.float_vel
%   passive.spar_pos
%   passive.spar_vel
%
% Sign convention:
%
%   Force applied by PTO to WEC:
%
%       F_total = -Bpto*v_rel + F_PI
%
%   Positive absorbed PTO power:
%
%       p_net = Bpto*v_rel.^2 - F_PI.*v_rel
%
% Operating point:
%
%   omega0  = 4 rad/s
%   H       = 0.32 m
%   rampTime = 30 s

clearvars -except output waves simu pto body constraint
close all
clc


%% ================================================================
%  USER SETTINGS
%  ================================================================

omega0 = 4;                  % wave frequency [rad/s]
Bpto = 540;                  % passive PTO damping [N s/m]
rampTime = 30;               % WEC-Sim ramp time [s]

NcyclesAverage = 30;         % cycles used for average metrics
NcyclesPlot = 5;             % cycles shown in steady-state plots

saveFigures = true;
saveSummary = true;

pngResolution = 300;


%% ================================================================
%  PATHS
%  ================================================================

thisFile = mfilename('fullpath');

if isempty(thisFile)
    % Fallback if running an unsaved copy
    thisDir = pwd;
else
    thisDir = fileparts(thisFile);
end

piFile = fullfile(thisDir, 'PI_run_ramped.mat');
passiveFile = fullfile(thisDir, 'passive_SD_run.mat');

figDir = fullfile(thisDir, 'report_figures');


if ~isfile(piFile)

    error(['PI data file not found:\n  %s\n\n' ...
        'Place PI_run_ramped.mat in the same folder as this script.'], ...
        piFile);

end


if ~isfile(passiveFile)

    [f,p] = uigetfile('*.mat', ...
        'Select passive_SD_run.mat');

    if isequal(f,0)
        error('Passive SD data file was not selected.');
    end

    passiveFile = fullfile(p,f);

end


if saveFigures && ~exist(figDir,'dir')
    mkdir(figDir);
end


%% ================================================================
%  LOAD DATA
%  ================================================================

PI = load(piFile);
PAS = load(passiveFile);


requiredPI = {'v_ref','v_rel','error','F_PI'};

for k = 1:numel(requiredPI)

    if ~isfield(PI,requiredPI{k})

        error('PI_run_ramped.mat is missing variable "%s".', ...
            requiredPI{k});

    end

end


if ~isfield(PAS,'passive')

    error(['passive_SD_run.mat must contain a structure ' ...
        'named "passive".']);

end

passive = PAS.passive;


%% ================================================================
%  EXTRACT PI SIGNALS
%  ================================================================

tRef = PI.v_ref.Time(:);

vRef = squeeze(PI.v_ref.Data);
vRef = vRef(:);


tPIv = PI.v_rel.Time(:);

vPI = squeeze(PI.v_rel.Data);
vPI = vPI(:);


tErr = PI.error.Time(:);

ePI = squeeze(PI.error.Data);
ePI = ePI(:);


tFpi = PI.F_PI.Time(:);

Fpi = squeeze(PI.F_PI.Data);
Fpi = Fpi(:);


%% ================================================================
%  EXTRACT PASSIVE SIGNALS
%  ================================================================

if ~isfield(passive,'time') || ~isfield(passive,'v_rel')

    error(['The passive structure must contain ' ...
        'passive.time and passive.v_rel.']);

end


tPAS = passive.time(:);
vPAS = passive.v_rel(:);


if isfield(passive,'Bpto') && ~isempty(passive.Bpto)

    BptoPAS = passive.Bpto;

else

    BptoPAS = Bpto;

end


%% ================================================================
%  COMMON STEADY-STATE ANALYSIS WINDOW
%  ================================================================

T = 2*pi/omega0;


tEnd = min([ ...
    tRef(end), ...
    tPIv(end), ...
    tFpi(end), ...
    tPAS(end)]);


availableCycles = floor((tEnd-rampTime)/T);


if availableCycles < 1

    error('Not enough post-ramp data for steady-state analysis.');

end


Navg = min(NcyclesAverage,availableCycles);
Nplot = min(NcyclesPlot,availableCycles);


tAvg1 = tEnd - Navg*T;
tPlot1 = tEnd - Nplot*T;


% Uniform time grids
tAvg = linspace( ...
    tAvg1, ...
    tEnd, ...
    max(5000,Navg*1000)).';


tPlot = linspace( ...
    tPlot1, ...
    tEnd, ...
    max(2000,Nplot*1000)).';


%% ================================================================
%  INTERPOLATE SIGNALS
%  ================================================================

% ---------------- Average window ----------------

vRefAvg = interp1( ...
    tRef, ...
    vRef, ...
    tAvg, ...
    'pchip');


vPIAvg = interp1( ...
    tPIv, ...
    vPI, ...
    tAvg, ...
    'pchip');


ePIAvg = interp1( ...
    tErr, ...
    ePI, ...
    tAvg, ...
    'pchip');


FpiAvg = interp1( ...
    tFpi, ...
    Fpi, ...
    tAvg, ...
    'pchip');


vPASAvg = interp1( ...
    tPAS, ...
    vPAS, ...
    tAvg, ...
    'pchip');


% ---------------- Plot window ----------------

vRefPlot = interp1( ...
    tRef, ...
    vRef, ...
    tPlot, ...
    'pchip');


vPIPlot = interp1( ...
    tPIv, ...
    vPI, ...
    tPlot, ...
    'pchip');


FpiPlot = interp1( ...
    tFpi, ...
    Fpi, ...
    tPlot, ...
    'pchip');


vPASPlot = interp1( ...
    tPAS, ...
    vPAS, ...
    tPlot, ...
    'pchip');


%% ================================================================
%  FORCE AND POWER
%  ================================================================

% ------------------------------------------------
% Passive SD case
% ------------------------------------------------

% PTO force applied to the WEC
FpasAvg = -BptoPAS*vPASAvg;

% Positive absorbed power
PpasAvg_inst = BptoPAS*vPASAvg.^2;


FpasPlot = -BptoPAS*vPASPlot;

PpasPlot = BptoPAS*vPASPlot.^2;


% ------------------------------------------------
% PI-controlled case
% ------------------------------------------------

% Existing passive damping force
FdampPIAvg = -Bpto*vPIAvg;

% Total PTO force applied to WEC
FtotalPIAvg = FdampPIAvg + FpiAvg;


% Passive damping power
PdampPIAvg_inst = Bpto*vPIAvg.^2;

% Active PI power
%
% Positive  -> PI actuator absorbs energy
% Negative  -> PI actuator injects energy
PpiAvg_inst = -FpiAvg.*vPIAvg;

% Net absorbed PTO power
PnetPIAvg_inst = ...
    PdampPIAvg_inst + PpiAvg_inst;


% Plot-window quantities

FdampPIPlot = -Bpto*vPIPlot;

FtotalPIPlot = ...
    FdampPIPlot + FpiPlot;


PdampPIPlot = ...
    Bpto*vPIPlot.^2;


PpiPlot = ...
    -FpiPlot.*vPIPlot;


PnetPIPlot = ...
    PdampPIPlot + PpiPlot;


%% ================================================================
%  SUMMARY METRICS
%  ================================================================

avg = @(x) ...
    trapz(tAvg,x)/(tAvg(end)-tAvg(1));


rms_t = @(x) ...
    sqrt(avg(x.^2));


% ------------------------------------------------
% Average power
% ------------------------------------------------

P_passive = ...
    avg(PpasAvg_inst);


P_damp_PI = ...
    avg(PdampPIAvg_inst);


P_PI = ...
    avg(PpiAvg_inst);


P_net_PI = ...
    avg(PnetPIAvg_inst);


powerIncreasePct = ...
    100*(P_net_PI/P_passive - 1);


% Analytical conjugate-matching optimum
idealPower = 84.5365;


idealFractionPct = ...
    100*P_net_PI/idealPower;


% ------------------------------------------------
% Velocity metrics
% ------------------------------------------------

Vrms_passive = ...
    rms_t(vPASAvg);


Vrms_PI = ...
    rms_t(vPIAvg);


Erms_PI = ...
    rms_t(ePIAvg);


% ------------------------------------------------
% Peak forces
% ------------------------------------------------

Fpk_passive = ...
    max(abs(FpasAvg));


Fpk_PIact = ...
    max(abs(FpiAvg));


Fpk_PItotal = ...
    max(abs(FtotalPIAvg));


% ------------------------------------------------
% RMS forces
% ------------------------------------------------

Frms_passive = ...
    rms_t(FpasAvg);


Frms_PIact = ...
    rms_t(FpiAvg);


Frms_PItotal = ...
    rms_t(FtotalPIAvg);


%% ================================================================
%  DISPLAY SUMMARY
%  ================================================================

fprintf('\n');
fprintf('============================================================\n');

fprintf('PASSIVE SD vs PI-CONTROLLED WEC: STEADY-STATE SUMMARY\n');

fprintf( ...
    'Analysis window: %.4f to %.4f s (%d complete cycles)\n', ...
    tAvg1, ...
    tEnd, ...
    Navg);

fprintf('============================================================\n');


fprintf( ...
    'Average passive SD power       = %10.4f W\n', ...
    P_passive);


fprintf( ...
    'Average PI damping power       = %10.4f W\n', ...
    P_damp_PI);


fprintf( ...
    'Average PI actuator power      = %10.4f W\n', ...
    P_PI);


fprintf( ...
    'Average PI net PTO power       = %10.4f W\n', ...
    P_net_PI);


fprintf( ...
    'Net power increase vs passive  = %10.2f %%\n', ...
    powerIncreasePct);


fprintf( ...
    'PI net / ideal optimum         = %10.2f %%\n', ...
    idealFractionPct);


fprintf('\n');


fprintf( ...
    'RMS v_rel, passive             = %10.4f m/s\n', ...
    Vrms_passive);


fprintf( ...
    'RMS v_rel, PI                  = %10.4f m/s\n', ...
    Vrms_PI);


fprintf( ...
    'RMS PI tracking error          = %10.4f m/s\n', ...
    Erms_PI);


fprintf('\n');


fprintf( ...
    'Peak |F_PTO|, passive          = %10.4f N\n', ...
    Fpk_passive);


fprintf( ...
    'Peak |F_PI|                    = %10.4f N\n', ...
    Fpk_PIact);


fprintf( ...
    'Peak |F_total|, PI             = %10.4f N\n', ...
    Fpk_PItotal);


fprintf('============================================================\n');
fprintf('\n');


%% ================================================================
%  REPORT PLOT STYLE
%  ================================================================

fontName = 'Times New Roman';
fontSize = 11;
lineWidth = 1.5;


% Consistent report colors
cPassive = [0.20 0.20 0.20];

cPI = [0.00 0.45 0.74];

cRef = [0.85 0.33 0.10];

cActive = [0.49 0.18 0.56];

cNet = [0.47 0.67 0.19];


%% ================================================================
%  FIGURE 1
%  PI TRACKING - FULL SIMULATION
%  ================================================================

fig1 = figure( ...
    'Color','w', ...
    'Name','PI Tracking - Full Simulation');


plot( ...
    tRef, ...
    vRef, ...
    '--', ...
    'LineWidth',lineWidth, ...
    'Color',cRef);

hold on


plot( ...
    tPIv, ...
    vPI, ...
    'LineWidth',lineWidth, ...
    'Color',cPI);


grid on


xlabel( ...
    'Time (s)', ...
    'Interpreter','latex');


ylabel( ...
    'Relative velocity (m/s)', ...
    'Interpreter','latex');


legend( ...
    {'$v_{\mathrm{ref}}$', ...
     '$v_{\mathrm{rel,PI}}$'}, ...
    'Interpreter','latex', ...
    'Location','best');


title( ...
    'PI-Controlled Relative-Velocity Tracking', ...
    'Interpreter','latex');


xlim([0 tEnd]);


set( ...
    gca, ...
    'FontName',fontName, ...
    'FontSize',fontSize, ...
    'Box','on');


%% ================================================================
%  FIGURE 2
%  STEADY-STATE RELATIVE VELOCITY COMPARISON
%  ================================================================

fig2 = figure( ...
    'Color','w', ...
    'Name','Relative Velocity Comparison');


plot( ...
    tPlot, ...
    vPASPlot, ...
    'LineWidth',lineWidth, ...
    'Color',cPassive);

hold on


plot( ...
    tPlot, ...
    vPIPlot, ...
    'LineWidth',lineWidth, ...
    'Color',cPI);


plot( ...
    tPlot, ...
    vRefPlot, ...
    '--', ...
    'LineWidth',lineWidth, ...
    'Color',cRef);


grid on


xlabel( ...
    'Time (s)', ...
    'Interpreter','latex');


ylabel( ...
    'Relative velocity (m/s)', ...
    'Interpreter','latex');


legend( ...
    {'Passive SD', ...
     'PI controlled', ...
     '$v_{\mathrm{ref}}$'}, ...
    'Interpreter','latex', ...
    'Location','best');


title( ...
    sprintf( ...
    'Steady-State Relative Velocity (%d Wave Periods)', ...
    Nplot), ...
    'Interpreter','latex');


xlim([tPlot(1) tPlot(end)]);


set( ...
    gca, ...
    'FontName',fontName, ...
    'FontSize',fontSize, ...
    'Box','on');


%% ================================================================
%  FIGURE 3
%  PTO FORCE COMPARISON
%  ================================================================

fig3 = figure( ...
    'Color','w', ...
    'Name','PTO Force Comparison');


plot( ...
    tPlot, ...
    FpasPlot, ...
    'LineWidth',lineWidth, ...
    'Color',cPassive);

hold on


plot( ...
    tPlot, ...
    FtotalPIPlot, ...
    'LineWidth',lineWidth, ...
    'Color',cPI);


plot( ...
    tPlot, ...
    FpiPlot, ...
    '--', ...
    'LineWidth',1.2, ...
    'Color',cActive);


grid on


xlabel( ...
    'Time (s)', ...
    'Interpreter','latex');


ylabel( ...
