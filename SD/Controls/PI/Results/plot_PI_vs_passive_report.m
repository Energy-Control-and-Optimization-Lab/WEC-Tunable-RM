     '$F_{\mathrm{PI}}$'}, ...
    'Interpreter','latex', ...
    'Location','best');


title( ...
    sprintf( ...
    'Steady-State PTO Force (%d Wave Periods)', ...
    Nplot), ...
    'Interpreter','latex');


xlim([tPlot(1) tPlot(end)]);


set( ...
    gca, ...
    'FontName',fontName, ...
    'FontSize',fontSize, ...
    'Box','on');


%% ================================================================
%  FIGURE 4
%  INSTANTANEOUS NET ABSORBED POWER COMPARISON
%  ================================================================

fig4 = figure( ...
