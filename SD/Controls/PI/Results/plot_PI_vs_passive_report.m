    'Interpreter','latex');


legend( ...
    {'Passive SD', ...
     'PI-controlled net'}, ...
    'Interpreter','latex', ...
    'Location','best');


title( ...
    sprintf( ...
    'Steady-State Net PTO Power (%d Wave Periods)', ...
    Nplot), ...
    'Interpreter','latex');


xlim([tPlot(1) tPlot(end)]);


