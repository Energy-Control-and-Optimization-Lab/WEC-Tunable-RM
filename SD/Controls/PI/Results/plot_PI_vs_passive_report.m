%% ================================================================
%  FIGURE 6
%  AVERAGE NET PTO POWER
%
%  ORDER:
%  1. Passive SD
%  2. PI controlled
%  ================================================================

fig6 = figure( ...
    'Color','w', ...
    'Name','Average Net PTO Power');


% Explicit category order
powerCats = categorical( ...
    {'Passive SD','PI controlled'});


powerCats = reordercats( ...
    powerCats, ...
    {'Passive SD','PI controlled'});


powerVals = [ ...
    P_passive, ...
    P_net_PI];


