    text( ...
        k, ...
        powerVals(k)+labelOffset, ...
        sprintf('%.2f W',powerVals(k)), ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','bottom', ...
        'FontName',fontName, ...
        'FontSize',fontSize);

end


